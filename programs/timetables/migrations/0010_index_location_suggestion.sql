-- 「科目名から追加」の教室の自動入力候補（findCommonLocationForCourse、functions/api/_lib/db/users.ts）用の索引。
--
-- 候補は「同じ学期・曜日・時限・科目名・担当教員」の他の学生の行から探すが、これまでこの条件に使える索引が無く、
-- 1回の問い合わせごとに timetable_entries を全件読んでいた（検索結果1行につき1回、1回の検索で最大30回）。
-- D1 は読んだ行数で課金・無料枠の上限が決まるため、登録者が増えるほど読み取りが登録者数の2乗で増え、
-- 無料プランでは登録が集中する日に上限に達して止まる・有料プランでは費用が急に増える原因になっていた。
-- この索引で、同じ授業の行だけを読むようになる（2,000人・30,000行のテストデータで、1回あたり30,000行 → 数行）。
--
-- 既存のデータは変更しない（索引を足すだけ）。デプロイとの順番はどちらが先でもよい
-- （索引が無くても動作は同じで、遅く・読み取りが多くなるだけ）。
-- 代わりに、時間割の行を書き換えるたびに索引の分の書き込みが1行増える（D1 は索引1つにつき1行と数える）。

CREATE INDEX IF NOT EXISTS idx_entries_course_slot
  ON timetable_entries(term, day_of_week, period, course_name, instructor);
