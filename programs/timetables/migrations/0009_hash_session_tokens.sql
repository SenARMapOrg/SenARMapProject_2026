-- セッションIDのハッシュ化（2026-09-26）。
--
-- これまで sessions.id には Cookie に入れるトークンそのものを保存していた。今後は SHA-256 ハッシュだけを
-- 保存する（functions/api/_lib/db/sessions.ts）。DB を読める人がいても、そこからログイン中の人に
-- なりすませないようにするため。
--
-- 保存形式が変わるので、既存のセッション（生のトークンのまま保存されている行）は使えなくなる。
-- 新しいコードはトークンをハッシュしてから探すので、生のトークンの行とは一致しない（=残しておいても
-- ログインには使われない）が、トークンが平文で残り続けないようにここで消す。
--
-- 消えるのはログイン状態だけで、ユーザー・時間割・公開設定・友達・閲覧記録には一切触れない。
-- 全員が一度ログアウトされ、ログインし直すと Google アカウントの ID（users.google_sub）で
-- 同じユーザーに戻るので、自分のデータがそのまま表示される。
-- 適用はデプロイの前後どちらでもよい（新しいコードは古い行を使わないため）。
DELETE FROM sessions;
